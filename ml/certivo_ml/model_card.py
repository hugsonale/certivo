"""Writes the model card of an evaluated model from its metrics file, so the card can never disagree with the numbers.

The card is committed to git (it is text). It contains no date and no commit id, so regenerating it from the same code and the
same data gives the same bytes, which is what lets "dvc repro" prove that a clean checkout reproduces it.
"""

from __future__ import annotations

import json
import re
from typing import Any

from . import DATASET, MODEL, ROOT, write_text
from .params import load_params

TEMPLATE = ROOT / "model_cards" / "TEMPLATE.md"
CARD = ROOT / "model_cards" / f"{MODEL}.md"
METRICS = ROOT / "metrics" / f"{MODEL}.json"

REQUIRED_HEADINGS = [
    "Model details",
    "Intended use",
    "Not for",
    "Training data",
    "Evaluation",
    "Limits and risks",
    "Fairness and robustness",
    "Promotion status",
    "Reproduce",
    "Licence and provenance",
]
# Words that claim more than a measurement can. A card may describe results, never boast (guide Part 3: no unsubstantiated accuracy).
FORBIDDEN = re.compile(r"\b(state[- ]of[- ]the[- ]art|production[- ]ready|human[- ]level|guarantee[sd]?|best[- ]in[- ]class)\b", re.I)


def _percent(rate: dict[str, Any]) -> str:
    low, high = rate["ci95"]
    return f"{rate['value'] * 100:.1f}% ({rate['count']} of {rate['of']}; 95% interval {low * 100:.1f}% to {high * 100:.1f}%)"


def _table(block: dict[str, Any]) -> str:
    c = block["confusion"]
    rows = [
        ("Accuracy", _percent(block["accuracy"])),
        ("False positive rate", _percent(block["false_positive_rate"])),
        ("False negative rate", _percent(block["false_negative_rate"])),
        ("AUC", f"{block['auc']:.3f}"),
        ("Log loss", f"{block['log_loss']:.3f}"),
        ("Calibration error (10 slices)", f"{block['expected_calibration_error']:.3f}"),
        ("Counts (true pos / false pos / true neg / false neg)", f"{c['true_positive']} / {c['false_positive']} / {c['true_negative']} / {c['false_negative']}"),
    ]
    return "| Measure | Result |\n| :-- | :-- |\n" + "\n".join(f"| {k} | {v} |" for k, v in rows)


def _group_table(groups: dict[str, Any]) -> str:
    lines = ["| Group | Pictures | Accuracy | False positive rate | False negative rate |", "| :-- | --: | :-- | :-- | :-- |"]
    for name, block in groups.items():
        lines.append(
            f"| {name} | {block['samples']} | {_percent(block['accuracy'])} | {_percent(block['false_positive_rate'])} | {_percent(block['false_negative_rate'])} |"
        )
    return "\n".join(lines)


def render(metrics: dict[str, Any], template: str | None = None) -> str:
    params = load_params()
    template = template if template is not None else TEMPLATE.read_text(encoding="utf-8")
    split = metrics["samples"]
    values = {
        "name": metrics["model"],
        "banner": (
            "**This model was trained and tested on SYNTHETIC data generated by this repository. It exists to test the ML workspace. "
            "It says nothing about how well any real model would work on real people, and no accuracy claim may be made from it.**"
        ),
        "kind": "Nearest-class-average classifier with a calibrated temperature (plain NumPy, no learned layers).",
        "io": "Input: a 16x16 grey picture. Output: a score and a probability that the picture carries the faint central stamp.",
        "training": "`dvc repro` in `ml/`: generate the data, train on the training split, pick the temperature on the validation split, evaluate once on the test split.",
        "intended_use": "To prove that experiments in this repository can be tracked, versioned and reproduced from a clean checkout, and as the first line in the "
        "comparison table of later models.",
        "out_of_scope": "Anything to do with real faces, real calls, liveness or deepfake detection. It has never seen a person and must not be described as detecting anything.",
        "dataset": metrics["dataset"],
        "datasheet": f"ml/datasheets/{metrics['dataset']}.md",
        "data_sha256": metrics["data_sha256"],
        "data_origin": "Generated by `ml/certivo_ml/synthetic.py` from a fixed seed. No person, no face, no scraped or licensed data.",
        "split": f"{split['train']} training, {split['val']} validation, {split['test']} test.",
        "evaluation_table": _table(metrics["test"]),
        "group_table": _group_table(metrics["test_by_group"]),
        "limits": "The task is easy and artificial. The groups are invented, and the third was given more noise on purpose, so differences between groups here "
        "show that the reporting works, not that any real group is treated worse.",
        "fairness": "Not evaluated. A fairness and robustness evaluation on real subgroups, devices and compression levels is step P0-39 and needs real data.",
        "promotion": "**Not promoted.** No external claim may be made about this model. Promotion needs the gate of step P0-40 (detection latency and false-trigger "
        "rate measured and recorded), which a synthetic model cannot pass.",
        "reproduce": "```\ncd ml\npip install -r requirements.txt -c constraints.txt\ndvc repro\n```\nA clean checkout must give this card and the metrics file unchanged.",
        "licence": "Code: the repository's licence. Data: generated, no third-party rights. No model weights are committed; they are rebuilt by `dvc repro`.",
    }
    text = template
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    return text


def validate(text: str) -> list[str]:
    """What is wrong with a model card, as plain sentences. An empty list means it is acceptable."""
    problems = []
    for heading in REQUIRED_HEADINGS:
        if not re.search(rf"^## {re.escape(heading)}\s*$", text, re.M):
            problems.append(f'missing the section "{heading}"')
    if "{{" in text:
        problems.append("it still has an unfilled {{placeholder}}")
    for match in FORBIDDEN.finditer(text):
        problems.append(f'it uses a claim-making phrase: "{match.group(0)}"')
    if re.search(r"synthetic", text, re.I) and not re.search(r"says nothing about how well", text, re.I):
        problems.append("it is built on synthetic data but does not say that it says nothing about real-world performance")
    if not re.search(r"\*\*Not promoted\.\*\*", text) and not re.search(r"^Promoted", text, re.M):
        problems.append("its promotion status is not stated")
    return problems


def main() -> None:
    metrics = json.loads(METRICS.read_text(encoding="utf-8"))
    text = render(metrics)
    problems = validate(text)
    if problems:
        raise SystemExit("the model card is not acceptable:\n  - " + "\n  - ".join(problems))
    write_text(CARD, text)
    print(f"wrote {CARD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
