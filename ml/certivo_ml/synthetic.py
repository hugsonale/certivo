"""Makes the synthetic dataset. It is generated, never collected: no person, no face, no real footage is involved.

The task: tell 16x16 grey pictures that have a faint square "stamp" in the middle (label 1) from pictures that do not (label 0).
Every picture also has a smooth gradient and random noise, and the noise level depends on a made-up "device" group (0, 1, 2),
so the third group is harder than the first. That gives the baseline model, the metrics and the per-group report something to do.

The output is the same bytes on every machine, because NumPy's random generator is specified exactly and the files are plain
.npy arrays with no timestamps.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

import numpy as np

from . import DATASET, ROOT, write_text
from .params import load_params

SPLITS = {"train": 0, "val": 1, "test": 2}


def generate(config: dict[str, Any]) -> dict[str, np.ndarray]:
    rng = np.random.default_rng(config["seed"])
    n = int(config["samples"])
    side = int(config["side"])
    noise = np.asarray(config["group_noise"], dtype=np.float64)

    # exactly half of each label, in a random order
    labels = np.zeros(n, dtype=np.uint8)
    labels[: n // 2] = 1
    labels = labels[rng.permutation(n)]
    groups = rng.integers(0, len(noise), size=n).astype(np.uint8)

    # a smooth left-to-right gradient, the same for every picture
    gradient = np.tile(np.linspace(60, 120, side), (side, 1))
    low, high = side // 2 - 3, side // 2 + 3
    stamp = np.zeros((side, side))
    stamp[low:high, low:high] = float(config["stamp_amplitude"])

    pictures = gradient[None, :, :] + labels[:, None, None] * stamp[None, :, :]
    pictures = pictures + rng.normal(size=(n, side, side)) * noise[groups][:, None, None]
    images = np.clip(np.rint(pictures), 0, 255).astype(np.uint8)

    # which pictures are for training, checking and the final test
    fractions = config["split"]
    order = rng.permutation(n)
    n_train = int(round(n * fractions["train"]))
    n_val = int(round(n * fractions["val"]))
    split = np.empty(n, dtype=np.uint8)
    split[order[:n_train]] = SPLITS["train"]
    split[order[n_train : n_train + n_val]] = SPLITS["val"]
    split[order[n_train + n_val :]] = SPLITS["test"]
    return {"images": images, "labels": labels, "groups": groups, "split": split}


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_dataset(arrays: dict[str, np.ndarray], out: Path, config: dict[str, Any]) -> dict[str, Any]:
    out.mkdir(parents=True, exist_ok=True)
    files: dict[str, str] = {}
    for name, array in arrays.items():
        path = out / f"{name}.npy"
        np.save(path, array, allow_pickle=False)
        files[path.name] = sha256_of(path)
    manifest = {
        "dataset": DATASET,
        "kind": "synthetic: generated by this repository, contains no people",
        "samples": int(arrays["labels"].shape[0]),
        "files_sha256": files,
        "generator_params": config,
    }
    write_text(out / "MANIFEST.json", json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return manifest


def data_sha256(directory: Path) -> str:
    """One fingerprint for the whole dataset: the fingerprints of its files, in name order, hashed together."""
    digest = hashlib.sha256()
    for path in sorted(directory.glob("*.npy")):
        digest.update(path.name.encode())
        digest.update(sha256_of(path).encode())
    return digest.hexdigest()


def load_dataset(directory: Path) -> dict[str, np.ndarray]:
    return {name: np.load(directory / f"{name}.npy", allow_pickle=False) for name in ("images", "labels", "groups", "split")}


def main() -> None:
    config = load_params()["synthetic"]
    manifest = write_dataset(generate(config), ROOT / "data" / DATASET, config)
    print(f"wrote {manifest['samples']} synthetic pictures to data/{DATASET}")


if __name__ == "__main__":
    main()
